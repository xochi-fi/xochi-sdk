/**
 * Fee schedule conformance against the shared spec vector.
 *
 * Binds `src/tiers.ts` to `@xochi/spec`'s `fee/schedule.json` cell-for-cell; Riddler binds
 * itself to the same file via `fee_conformance_test.exs`, so the two cannot disagree without
 * something going red (riddler#753: both sides passed their own tests for nine days while
 * disagreeing).
 *
 * WHY THIS FAILS RATHER THAN SKIPS when the vector is missing: an absent input and a passing
 * check must not look alike. The vector comes from the `@xochi/spec` workspace in this repo
 * (`packages/spec/fee/schedule.json`, regenerated by `npm run generate:fee` and gated in CI),
 * never from a sibling checkout or an env override.
 *
 * WHY A TEST AND NOT A DERIVATION: reading the schedule from the JSON would make `@xochi/spec`
 * a runtime dependency of `@xochi/sdk` for nine numbers.
 */

import { describe, it, expect } from "vitest";
import { createRequire } from "node:module";
import { FEE_SCHEDULE, SURPLUS_SHARE_PCT, TRUST_THRESHOLDS } from "../src/tiers.js";
import type { TierName, AssetClass } from "../src/tiers.js";

const require = createRequire(import.meta.url);

interface Vector {
  surplus_share_pct: number;
  tier_boundaries: Array<{ tier: string; min_trust_score: number }>;
  solver_base_bps: Record<AssetClass, number>;
  venue_bps: Record<string, Record<AssetClass, number>>;
  routing_bps: Record<string, Record<AssetClass, number>>;
}

const vector = require("@xochi/spec/fee/schedule.json") as Vector;

/** The vector keys tiers lowercase; this module keys them by TierName. */
const TIER_KEYS: ReadonlyArray<[TierName, string]> = [
  ["Standard", "standard"],
  ["Trusted", "trusted"],
  ["Verified", "verified"],
  ["Premium", "premium"],
  ["Institutional", "institutional"],
];

const CLASSES: readonly AssetClass[] = ["stable", "volatile"];

describe("fee schedule conforms to @xochi/spec vector", () => {
  it("every layer of every tier matches, on both asset classes", () => {
    const v = vector;
    for (const [tierName, key] of TIER_KEYS) {
      for (const cls of CLASSES) {
        const mine = FEE_SCHEDULE[tierName][cls];
        expect(mine.solverBps, `${tierName}/${cls} solver`).toBe(v.solver_base_bps[cls]);
        expect(mine.venueBps, `${tierName}/${cls} venue`).toBe(v.venue_bps[key][cls]);
        expect(mine.routingBps, `${tierName}/${cls} routing`).toBe(v.routing_bps[key][cls]);
      }
    }
  });

  it("tier score boundaries match", () => {
    const v = vector;
    const byTier = Object.fromEntries(v.tier_boundaries.map((b) => [b.tier, b.min_trust_score]));
    expect(byTier.standard).toBe(0);
    expect(byTier.trusted).toBe(TRUST_THRESHOLDS.trusted);
    expect(byTier.verified).toBe(TRUST_THRESHOLDS.verified);
    expect(byTier.premium).toBe(TRUST_THRESHOLDS.premium);
    expect(byTier.institutional).toBe(TRUST_THRESHOLDS.institutional);
  });

  it("surplus share matches", () => {
    expect(SURPLUS_SHARE_PCT).toBe(vector.surplus_share_pct);
  });
});
