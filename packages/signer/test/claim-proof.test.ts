/**
 * Claim-prepare ownership proof (Riddler#993, #1103) against SERVER-generated
 * vectors.
 *
 * `test/vectors/claim_prepare_proof.json` is a byte copy of Riddler's
 * `priv/conformance/claim_prepare_proof.json`, the same artifact Riddler serves
 * at `/xochi/vectors/claim-prepare-proof.json` and pins in
 * `conformance_vectors_test.exs`. Nothing here recomputes it: a test that
 * rebuilds the challenge string itself agrees with the signer by construction.
 *
 * The SDK signs only `transfer` (v1) and `approve_permit2` (v2). The v3 `call`
 * and v4 `batch` vectors are out of scope for `ClaimAction` and are skipped by
 * action, not by name.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { ethers } from "ethers";
import { claimPrepareChallenge, signClaimPrepareProof, type ClaimAction } from "@xochi/signer";

const here = dirname(fileURLToPath(import.meta.url));
const fixture = JSON.parse(
  readFileSync(join(here, "vectors", "claim_prepare_proof.json"), "utf-8"),
) as {
  vectors: Array<{
    name: string;
    challenge: string;
    digest: string;
    signature: string;
    signer: string;
    private_key: string;
    inputs: {
      action: string;
      chain_id: number;
      counterfactual: string;
      recipient: string;
      issued_at: number;
    };
  }>;
};

const SUPPORTED: readonly string[] = ["transfer", "approve_permit2"] satisfies ClaimAction[];
const inScope = fixture.vectors.filter((v) => SUPPORTED.includes(v.inputs.action));

const params = (v: (typeof inScope)[number]) => ({
  chainId: v.inputs.chain_id,
  counterfactualAddress: v.inputs.counterfactual,
  recipientAddress: v.inputs.recipient,
  issuedAt: v.inputs.issued_at,
  action: v.inputs.action as ClaimAction,
});

describe("claim-prepare proof vectors (generated by the server)", () => {
  it("covers both supported challenge versions", () => {
    // A vendored refresh that dropped every v2 vector would otherwise pass
    // vacuously over the action the v2 challenge exists to bind.
    expect(new Set(inScope.map((v) => v.inputs.action))).toEqual(new Set(SUPPORTED));
  });

  it.each(inScope.map((v) => [v.name, v] as const))(
    "%s: challenge, digest, signature and signer",
    (_name, v) => {
      const challenge = claimPrepareChallenge(params(v));
      expect(challenge).toBe(v.challenge);
      expect(ethers.keccak256(ethers.toUtf8Bytes(challenge))).toBe(v.digest);

      const sig = signClaimPrepareProof(v.private_key, params(v));
      expect(sig.toLowerCase()).toBe(v.signature.toLowerCase());
      expect(ethers.recoverAddress(v.digest, sig).toLowerCase()).toBe(v.signer.toLowerCase());
    },
  );
});
